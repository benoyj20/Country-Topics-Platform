import nextVitals from "eslint-config-next/core-web-vitals";
import nextTypescript from "eslint-config-next/typescript";
import { defineConfig, globalIgnores } from "eslint/config";

// The backend answers no HTML (ADR 0014): the pages and the admin are the
// frontend's, so nothing here renders a page or loads what one would.
const NO_HTML =
  "The backend answers only JSON and files (ADR 0014); pages belong in apps/frontend.";

const HTML_PATHS = [
  "react",
  "react-dom",
  "next/dynamic",
  "next/font",
  "next/head",
  "next/image",
  "next/link",
  "next/navigation",
  "next/script",
  "@payloadcms/next/css",
  "@payloadcms/next/layouts",
  "@payloadcms/next/views",
  "@payloadcms/richtext-lexical/client",
  "@payloadcms/richtext-lexical/react",
  "@payloadcms/ui",
].map((name) => ({ name, message: NO_HTML }));

const HTML_PATTERNS = [
  {
    group: [
      "react/*",
      "react-dom/*",
      "next/font/*",
      "@payloadcms/ui/*",
      "*.css",
      "*.scss",
    ],
    message: NO_HTML,
  },
];

/**
 * The import rule for some files: what renders a page, and what those
 * files must leave to others (ADR 0015). A file's own rule replaces the
 * general one, so each repeats the list above.
 */
function restricted(...patterns) {
  return [
    "error",
    { paths: HTML_PATHS, patterns: [...HTML_PATTERNS, ...patterns] },
  ];
}

export default defineConfig([
  ...nextVitals,
  ...nextTypescript,
  {
    rules: {
      "no-restricted-imports": restricted(),
      "no-restricted-syntax": [
        "error",
        { selector: "JSXElement, JSXFragment", message: NO_HTML },
      ],
    },
  },
  // Each public page's data is its own (ADR 0015): the pages share the read
  // model's building blocks, never each other's modules. Only cached.ts,
  // which caches each page's loader, names them all.
  {
    files: ["src/public/**"],
    ignores: ["src/public/cached.ts"],
    rules: {
      "no-restricted-imports": restricted({
        group: ["*-page", "files", "browse", "browse-terms"].flatMap((page) => [
          `./${page}`,
          `@/public/${page}`,
        ]),
        message:
          "One page's data does not use another's (ADR 0015): move what both need into a shared module of the read model (see read.ts).",
      }),
    },
  },
  // Generated by `pnpm generate` and `pnpm migrate:create`.
  globalIgnores([
    ".next/",
    "next-env.d.ts",
    "src/payload-types.ts",
    "src/migrations/",
  ]),
]);
